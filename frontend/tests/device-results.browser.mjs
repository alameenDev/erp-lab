import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
await mkdir('test-results/device-results', {recursive: true});
const browser = await chromium.launch();
const page = await browser.newPage({viewport: {width: 1400, height: 1000}});
const errors = [];
page.on('pageerror', error => { errors.push(error.message); console.error(error.stack); });
page.on('console', message => { if (message.type() === 'error') console.error(message.text()); });
const inbox = () => page.getByTestId('device-results-inbox');
const rows = () => page.locator('tr[data-result-id]');
const waitIds = ids => page.waitForFunction(ids => JSON.stringify(Array.from(document.querySelectorAll('tr[data-result-id]'), row => Number(row.dataset.resultId))) === JSON.stringify(ids), ids);
const button = name => page.getByRole('button', {name, exact: true});
try {
  await page.goto('http://127.0.0.1:5173/tests/device-results-browser.html');
  const shortcut = page.getByTestId('device-results-shortcut');
  await shortcut.waitFor();
  assert.match(await shortcut.getAttribute('href'), /tab=results&status=all/);
  assert.equal(await shortcut.evaluate(el => el.nextElementSibling.getAttribute('href')), '/lab-settings');
  await shortcut.click();
  await waitIds(Array.from({length: 25}, (_, i) => i + 1));
  assert.equal(await page.evaluate(() => inboxFixture.store.resultsPagination.total), 32);
  assert.equal(await page.evaluate(() => inboxFixture.requests.filter(r => r.url === '/device-results').at(-1).params.status), undefined);
  assert.match(await rows().first().textContent(), /غير مرتبط بمريض/);
  assert.match(await rows().nth(1).textContent(), /اسم المريض غير متوفر/);
  assert.match(await rows().nth(2).textContent(), /مريض تجريبي 3/);
  assert.match(await rows().nth(3).textContent(), /تعذر النقل/);
  assert.equal(await button('استبدال نتيجة CBC بهذا الإرسال').count(), 0);
  const applyLabel = await page.evaluate(() => inboxFixture.t('apply_results'));
  assert.equal(await button(applyLabel).count(), 0);
  console.log('PASS: medical reports shortcut opens every status; names, barcodes and read-only permissions');

  const detailsButton = rows().nth(2).getByRole('button', {name: 'تفاصيل النتيجة'});
  await detailsButton.click();
  const detail = page.getByTestId('device-result-details');
  await detail.waitFor();
  for (const text of ['مريض تجريبي 3', '00000003', 'INV-3', 'White blood cells', '5.4', 'Review required', 'Sample checked']) assert.ok((await detail.textContent()).includes(text), text);
  await detail.locator('summary').filter({hasText: 'الرسالة الأصلية'}).click();
  assert.equal(await page.evaluate(() => window.inboxInjected), undefined);
  assert.ok((await detail.textContent()).includes('<script>'));
  await page.keyboard.press('Escape');
  await detail.waitFor({state: 'hidden'});
  assert.equal(await detailsButton.evaluate(el => document.activeElement === el), true);
  console.log('PASS: accessible details retain raw values, metadata, literal text and linked invoice barcode');

  await button('التالي').click();
  await waitIds([26, 27, 28, 29, 30, 31, 32]);
  await page.evaluate(() => { inboxFixture.store.startPolling(20); });
  await page.waitForFunction(() => inboxFixture.requests.filter(r => r.url === '/device-results' && r.params.page === 2).length >= 3);
  await page.evaluate(() => inboxFixture.store.stopPolling());
  await waitIds([26, 27, 28, 29, 30, 31, 32]);
  const search = page.getByRole('searchbox', {name: 'بحث باسم المريض أو الباركود'});
  await search.fill('00000003'); await button('بحث').click(); await waitIds([3]);
  assert.equal(await page.evaluate(() => inboxFixture.store.resultsPagination.current_page), 1);
  await button('تحديث النتائج').click(); await waitIds([3]);
  assert.equal(await page.evaluate(() => inboxFixture.store.resultsParams.search), '00000003');
  await search.fill('مريض تجريبي 32'); await button('بحث').click(); await waitIds([32]);
  await search.fill('');
  await page.getByLabel('الحالة', {exact: true}).selectOption('failed');
  await button('بحث').click(); await waitIds([4, 8, 12, 16, 20, 24, 28, 32]);
  console.log('PASS: pagination, search, status and polling preserve the active query');

  await page.evaluate(async () => {
    const slow = inboxFixture.store.GetDeviceResults({search: '00000001'});
    const fast = inboxFixture.store.GetDeviceResults({search: '00000003'});
    await Promise.all([slow, fast]);
  });
  await waitIds([3]);
  await page.evaluate(() => { inboxFixture.flags.fail = true; });
  await button('تحديث النتائج').click();
  await inbox().getByRole('alert').waitFor(); await waitIds([3]);
  await page.evaluate(() => { inboxFixture.flags.fail = false; });
  await button('تحديث النتائج').click();
  await inbox().getByRole('alert').waitFor({state: 'hidden'});
  console.log('PASS: stale responses cannot replace newer data; refresh errors are visible and recoverable');

  await page.evaluate(() => inboxFixture.router.replace({path: '/devices', query: {tab: 'results', status: 'pending,matched'}}));
  await waitIds([1, 2, 5, 6, 9, 10, 13, 14, 17, 18, 21, 22, 25, 26, 29, 30]);
  await page.evaluate(() => { inboxFixture.flags.edit = true; });
  await page.locator('tr[data-result-id="6"]').getByRole('button', {name: applyLabel, exact: true}).click();
  await waitIds([1, 2, 5, 9, 10, 13, 14, 17, 18, 21, 22, 25, 26, 29, 30]);
  assert.equal(await page.evaluate(() => inboxFixture.store.resultsParams.status), 'pending,matched');
  assert.equal(await page.evaluate(() => JSON.parse(inboxFixture.requests.find(r => r.url === '/device-results/6/apply').data).replace_existing), false);
  console.log('PASS: pending tab excludes completed deliveries; authorized apply preserves the current filter');
  await page.evaluate(() => { inboxFixture.flags.edit = false; });
  await button('جميع نتائج الأجهزة').click();
  await waitIds(Array.from({length: 25}, (_, i) => i + 1));
  await page.screenshot({path: 'test-results/device-results/desktop.png', fullPage: true, animations: 'disabled'});
  await page.setViewportSize({width: 390, height: 844});
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), 'mobile page should not overflow; only the table scrolls');
  await page.screenshot({path: 'test-results/device-results/mobile.png', fullPage: true, animations: 'disabled'});
  await rows().nth(2).getByRole('button', {name: 'تفاصيل النتيجة'}).click();
  await detail.waitFor();
  assert.ok(await detail.evaluate(el => el.getBoundingClientRect().right <= window.innerWidth), 'dialog fits mobile');
  await page.screenshot({path: 'test-results/device-results/mobile-details.png', animations: 'disabled'});
  await page.keyboard.press('Escape');
  await page.evaluate(() => inboxFixture.router.push('/medical_reports'));
  await shortcut.waitFor();
  assert.equal(await page.evaluate(() => inboxFixture.store.pollingInterval), null);
  await page.evaluate(async () => {
    inboxFixture.flags.slowDevices = true;
    await inboxFixture.router.push('/devices?tab=results&status=all');
    await inboxFixture.router.push('/medical_reports');
    await new Promise(resolve => setTimeout(resolve, 300));
  });
  assert.equal(await page.evaluate(() => inboxFixture.store.pollingInterval), null, 'late catalog load cannot restart polling after leaving');
  await page.evaluate(() => { inboxFixture.flags.view = false; });
  await shortcut.waitFor({state: 'hidden'});
  assert.deepEqual(errors, []);
  console.log('PASS: responsive inbox/details, polling cleanup, permission-gated shortcut, no runtime errors');
} catch (error) {
  console.error((await page.locator('body').textContent()).slice(0, 2500));
  await page.screenshot({path: 'test-results/device-results/failure.png'});
  throw error;
} finally { await browser.close(); }
